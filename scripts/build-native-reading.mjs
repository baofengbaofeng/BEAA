import {readFileSync,writeFileSync,readdirSync} from 'node:fs';
import {join} from 'node:path';
import {pinyin} from 'pinyin-pro';
const root=new URL('../apps/harmony/entry/src/main/ets/',import.meta.url);
function sources(path){return readdirSync(path,{withFileTypes:true}).flatMap(e=>e.isDirectory()?sources(join(path,e.name)):/\.(ets|ts)$/.test(e.name)&&e.name!=='NativeChineseReading.ts'?[join(path,e.name)]:[]);}
const {fileURLToPath}=await import('node:url');
const phrases=[...new Set(sources(fileURLToPath(root)).flatMap(path=>readFileSync(path,'utf8').match(/[\u3400-\u9fff]+/g)||[]))].sort();
const characters=[...new Set(phrases.join(''))].sort();
const entries=phrases.map(text=>[text,pinyin(text)]),chars=characters.map(text=>[text,pinyin(text)]);
const source=`/** Generated by scripts/build-native-reading.mjs using pinyin-pro; offline native display only. */
const PHRASES: { [key: string]: string } = ${JSON.stringify(Object.fromEntries(entries),null,2)};
const CHARACTERS: { [key: string]: string } = ${JSON.stringify(Object.fromEntries(chars),null,2)};
/** Reading first, original Chinese second. Never sends native text or credentials to the WebView. */
export function nativeReading(text: string): string {
  if(!/[\\u3400-\\u9fff]/.test(text))return text;
  const parts=text.match(/[\\u3400-\\u9fff]+|[^\\u3400-\\u9fff]+/g)||[];
  const reading=parts.map(part=>/[\\u3400-\\u9fff]/.test(part)?(PHRASES[part]||part.split('').map(char=>CHARACTERS[char]||'□').join(' ')):part).join(' ').replace(/ +/g,' ').trim();
  return reading+'\\n'+text;
}
`;
const output=new URL('services/NativeChineseReading.ts',root);
if(process.argv.includes('--check')) {
  if(readFileSync(output,'utf8')!==source)throw Error('Native reading map is stale; run node scripts/build-native-reading.mjs');
  console.log('Offline native readings match native source');
} else {
  writeFileSync(output,source);
  console.log(`Generated offline native readings: ${phrases.length} phrases, ${characters.length} characters`);
}
